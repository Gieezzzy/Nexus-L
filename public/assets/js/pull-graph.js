/* Pull Test Graph Report (Rivet, Velcro, Eyelet, Lace Holder, Heel Pull Tab, Tongue Pull Tab).
   One renderer used by Report Designer > Pull Test Graphs (preview) and Shoe Bonding (U60) > Generate Report (PNG).
   A layout is { v:1, w:1240, h:1754, cat, sources:{tables:[], joins:[]}, items:[...] }. */
(function () {
  'use strict';

  var FONT = '"Times New Roman", Times, serif';

  var CATEGORIES = [
    { key: 'rivet',           label: 'Rivet Graph',           title: 'VF Rivet Pull Test',                  testType: 'RIVET' },
    { key: 'velcro',          label: 'Velcro Graph',          title: 'VF Velcro Peel / Shear Test',         testType: 'VELCRO' },
    { key: 'eyelet',          label: 'Eyelet Graph',          title: 'VF Strap / Eyelet/Tongue Pull Test',  testType: 'EYELET' },
    { key: 'lace_holder',     label: 'Lace Holder Graph',     title: 'VF Lace Holder Pull Test',            testType: 'LACE LOOP HOLDER' },
    { key: 'heel_pull_tab',   label: 'Heel Pull Tab Graph',   title: 'VF Heel Pull Tab Test',               testType: 'HEEL PULL' },
    { key: 'tongue_pull_tab', label: 'Tongue Pull Tab Graph', title: 'VF Tongue Pull Tab Test',             testType: 'TONGUE PULL' }
  ];

  var CURVE_COLORS = [
    '#d62728', '#2ca02c', '#3b82f6', '#ec4899', '#94a3b8',
    '#10b981', '#d97706', '#78350f', '#8b5cf6', '#06b6d4',
    '#e11d48', '#16a34a', '#2563eb', '#db2777', '#64748b'
  ];

  function catMeta(cat) {
    for (var i = 0; i < CATEGORIES.length; i++) {
      if (CATEGORIES[i].key === cat) return CATEGORIES[i];
    }
    return CATEGORIES[2];
  }

  function defaultSources() {
    return {
      tables: ['tbl_dtr_pull_tests', '', ''],
      joins: [null, { leftTable: 0, leftCol: '', rightCol: '' }, { leftTable: 0, leftCol: '', rightCol: '' }]
    };
  }

  function defaultLayout(cat) {
    var m = catMeta(cat);
    return {
      v: 1,
      w: 1240,
      h: 1754,
      cat: m.key,
      sources: defaultSources(),
      items: [
        { id: 'title', type: 'text', x: 620, y: 48, w: 900, text: m.title, size: 32, bold: false, align: 'center', color: '#111111' },
        { id: 'sub', type: 'field', x: 620, y: 92, w: 900, template: '{Factory}', fallback: 'DATIAN SUBIC SHOES INC. (DTP)', size: 17, bold: false, align: 'center', color: '#6b7280' },
        {
          id: 'info', type: 'infogrid', x: 56, y: 128, w: 1128, size: 16, rowH: 28,
          left: [
            ['Laboratory ref.', '{LabRefNo}'],
            ['Model / style', '{ModelStyle}'],
            ['Color', '{Color}'],
            ['Equip code', '{EquipmentCode}'],
            ['Start time', '{StartTimestamp}']
          ],
          right: [
            ['Tested date', '{TestedDate}'],
            ['Machine No.', '{MachineName}'],
            ['Technician', '{Technician}'],
            ['Result', '{Result}'],
            ['End time', '{FinishTimestamp}']
          ]
        },
        {
          id: 'tbl', type: 'pulltable', x: 56, y: 284, w: 1128, size: 16, rowH: 28, headH: 30, maxRows: 30, showSummary: true,
          columns: [
            { label: 'Test NO.',             tpl: '{TestNo}',     w: 0.09, align: 'left' },
            { label: 'Speed',                tpl: '{SpeedStr}',   w: 0.12, align: 'left' },
            { label: 'Sample Name',          tpl: '{SampleName}', w: 0.36, align: 'left' },
            { label: 'Sample NO.',           tpl: '{SampleNo}',   w: 0.14, align: 'left' },
            { label: 'Peak kgf',             tpl: '{Peak}',       w: 0.14, align: 'left' },
            { label: 'Tensile Strength kgf', tpl: '{Tensile}',    w: 0.15, align: 'left' }
          ]
        },
        { id: 'graph', type: 'pullgraph', x: 56, y: 610, w: 1128, h: 430, yMax: 0, xMax: 0, xLabel: 'sec', yLabel: 'kgf', size: 14, markers: true, labels: true },
        { id: 'gen', type: 'field', x: 56, y: 1068, w: 1100, template: 'Generated by NEXUS-L on {now}  -  {LabRefNo}', size: 13, align: 'left', color: '#6b7280' }
      ]
    };
  }

  function num(v) {
    var n = parseFloat(String(v == null ? '' : v).replace(',', '.'));
    return isFinite(n) ? n : null;
  }

  function xy(str) {
    var p = String(str || '').split(';'), out = [];
    for (var i = 0; i + 1 < p.length; i += 2) {
      var a = num(p[i]), b = num(p[i + 1]);
      if (a != null && b != null) out.push([a, b]);
    }
    return out;
  }

  function lookup(data, key) {
    if (!data) return '';
    if (key === 'now') {
      var d = new Date(), z = function (n) { return String(n).padStart(2, '0'); };
      return d.getFullYear() + '-' + z(d.getMonth() + 1) + '-' + z(d.getDate()) + ' ' + z(d.getHours()) + ':' + z(d.getMinutes());
    }
    if (Object.prototype.hasOwnProperty.call(data, key) && data[key] != null) return String(data[key]);
    var dot = key.indexOf('.');
    if (dot !== -1) {
      var shortKey = key.slice(dot + 1);
      if (Object.prototype.hasOwnProperty.call(data, shortKey) && data[shortKey] != null) return String(data[shortKey]);
    }
    return '';
  }

  function fill(tpl, data, fallback) {
    var hasAny = false;
    var out = String(tpl == null ? '' : tpl).replace(/\{([A-Za-z0-9_.]+)\}/g, function (_, k) {
      var v = lookup(data, k);
      if (v !== '') hasAny = true;
      return v;
    });
    if (!hasAny && fallback) return fallback;
    return out;
  }

  function resultColor(text) {
    var t = String(text || '').toUpperCase();
    if (/\bFAIL/.test(t)) return '#c62828';
    if (/\bTOL/.test(t)) return '#e65100';
    if (/\bPASS/.test(t)) return '#16a34a';
    return null;
  }

  function extractRows(data, maxRows) {
    var rows = [];
    var limit = Math.min(30, Math.max(1, maxRows || 30));
    var sp = lookup(data, 'Speed');
    var spUnit = lookup(data, 'SpeedUnit') || 'mm/min';
    var speedStr = sp !== '' ? (sp + ' ' + spUnit) : '100 mm/min';
    var labRef = lookup(data, 'LabRefNo');
    for (var i = 1; i <= limit; i++) {
      var pk = num(lookup(data, 'Peak' + i));
      var sn = lookup(data, 'SampleNo' + i);
      var gr = lookup(data, 'Graph' + i);
      var pts = xy(gr);
      if (pk == null && sn === '' && pts.length < 2) continue;
      if (pk == null && pts.length) {
        pk = pts.reduce(function (m, p) { return p[1] > m ? p[1] : m; }, 0);
      }
      rows.push({
        idx: i,
        TestNo: String(rows.length + 1),
        SpeedStr: speedStr,
        SampleName: rows.length === 0 ? labRef : '',
        SampleNo: sn || String(i),
        Peak: pk != null ? pk.toFixed(2) : '',
        PeakNum: pk,
        Tensile: pk != null ? pk.toFixed(2) : '',
        pts: pts
      });
    }
    return rows;
  }

  function enrichData(raw) {
    var d = Object.assign({}, raw || {});
    var rows = extractRows(d, 30);
    var peaks = rows.map(function (r) { return r.PeakNum; }).filter(function (v) { return v != null; });
    if (peaks.length) {
      var mx = Math.max.apply(null, peaks);
      var mn = Math.min.apply(null, peaks);
      var avg = peaks.reduce(function (a, b) { return a + b; }, 0) / peaks.length;
      if (!d.MaxPeak) d.MaxPeak = mx.toFixed(2);
      if (!d.MinPeak) d.MinPeak = mn.toFixed(2);
      if (!d.AvgPeak) d.AvgPeak = avg.toFixed(2);
    } else {
      if (!d.MaxPeak) d.MaxPeak = '0.00';
      if (!d.MinPeak) d.MinPeak = '0.00';
      if (!d.AvgPeak) d.AvgPeak = '0.00';
    }
    if (!d.TestCountUsed) d.TestCountUsed = String(rows.length);
    if (!d.MachineName && d.EquipmentCode) d.MachineName = d.EquipmentCode;
    return d;
  }

  // ---- drawing helpers
  function font(ctx, size, bold) { ctx.font = (bold ? 'bold ' : '') + size + 'px ' + FONT; }
  function text(ctx, s, x, y, align, size, bold, color) {
    font(ctx, size, bold); ctx.fillStyle = color || '#111'; ctx.textAlign = align || 'left'; ctx.textBaseline = 'alphabetic';
    ctx.fillText(String(s == null ? '' : s), x, y);
  }
  function line(ctx, x1, y1, x2, y2, color, w) {
    ctx.beginPath(); ctx.moveTo(x1, y1); ctx.lineTo(x2, y2); ctx.strokeStyle = color || '#94a3b8'; ctx.lineWidth = w || 1; ctx.stroke();
  }

  function drawText(ctx, it, data) {
    var s = it.type === 'field' ? fill(it.template, data, it.fallback) : (it.text || '');
    var size = it.size || 18, col = it.color || '#111111';
    if (it.autoResult) col = resultColor(s) || col;
    text(ctx, s, it.x, it.y + size, it.align || 'left', size, !!it.bold, col);
  }

  function measureInfoGrid(it) {
    var L = (it.left || []).length, R = (it.right || []).length;
    return Math.max(1, Math.max(L, R)) * (it.rowH || 28);
  }

  function drawInfoGrid(ctx, it, data) {
    var sz = it.size || 16, rh = it.rowH || 28, w = it.w || 1128;
    var leftX = it.x, leftValX = it.x + Math.round(w * 0.16);
    var rightX = it.x + Math.round(w * 0.54), rightValX = it.x + Math.round(w * 0.70);
    var drawCol = function (pairs, lx, vx) {
      (pairs || []).forEach(function (pair, i) {
        var y = it.y + i * rh + sz + 4;
        var lbl = pair[0] || '', tpl = pair[1] || '';
        text(ctx, lbl, lx, y, 'left', sz, true, '#111111');
        var val = fill(tpl, data);
        var isRes = /result/i.test(lbl);
        var col = isRes ? (resultColor(val) || '#111111') : '#111111';
        text(ctx, val, vx, y, 'left', sz, isRes, col);
      });
    };
    drawCol(it.left, leftX, leftValX);
    drawCol(it.right, rightX, rightValX);
  }

  function measurePullTable(it, data) {
    var rows = extractRows(data, it.maxRows || 30);
    var count = Math.max(1, rows.length);
    var h = (it.headH || 30) + count * (it.rowH || 28);
    if (it.showSummary !== false) h += 30;
    return h;
  }

  function drawPullTable(ctx, it, data) {
    var rows = extractRows(data, it.maxRows || 30);
    var cols = (it.columns && it.columns.length) ? it.columns : defaultLayout(data.cat).items[3].columns;
    var w = it.w || 1128, hh = it.headH || 30, rh = it.rowH || 28, sz = it.size || 16;
    var totalW = cols.reduce(function (a, c) { return a + (Number(c.w) || 0.15); }, 0) || 1;
    var xs = [it.x];
    cols.forEach(function (c) { xs.push(xs[xs.length - 1] + ((Number(c.w) || 0.15) / totalW) * w); });

    var bodyCount = Math.max(1, rows.length);
    var tableH = hh + bodyCount * rh;

    // Header fill
    ctx.fillStyle = '#d6d3ce';
    ctx.fillRect(it.x, it.y, w, hh);
    ctx.strokeStyle = '#9ca3af';
    ctx.lineWidth = 1;
    ctx.strokeRect(it.x, it.y, w, tableH);
    line(ctx, it.x, it.y + hh, it.x + w, it.y + hh, '#9ca3af', 1);

    cols.forEach(function (c, i) {
      text(ctx, c.label || '', xs[i] + 8, it.y + hh - 9, 'left', sz, true, '#111111');
    });

    if (!rows.length) {
      text(ctx, 'No pull test readings found for this Lab Ref.', it.x + 12, it.y + hh + rh - 8, 'left', sz, false, '#6b7280');
    } else {
      rows.forEach(function (r, ri) {
        var rowTop = it.y + hh + ri * rh;
        var y = rowTop + rh - 8;
        if (ri > 0) line(ctx, it.x, rowTop, it.x + w, rowTop, '#e5e7eb', 1);
        var rowData = Object.assign({}, data, r);
        cols.forEach(function (c, ci) {
          var v = fill(c.tpl || '', rowData);
          text(ctx, v, xs[ci] + 8, y, 'left', sz, false, '#111111');
        });
      });
    }

    if (it.showSummary !== false) {
      var sy = it.y + tableH + 22;
      var sumTxt = 'Maximum ' + (data.MaxPeak || '0.00') + ' kgf     Minimum ' + (data.MinPeak || '0.00') + ' kgf     Average ' + (data.AvgPeak || '0.00') + ' kgf     ' + (data.TestCountUsed || rows.length) + ' test(s)';
      text(ctx, sumTxt, it.x, sy, 'left', sz, false, '#111111');
    }
  }

  function niceStep(maxVal, ticks) {
    if (maxVal <= 0) return 10;
    var raw = maxVal / ticks;
    var pow = Math.pow(10, Math.floor(Math.log10(raw)));
    var frac = raw / pow;
    var nice = frac <= 1 ? 1 : (frac <= 2 ? 2 : (frac <= 5 ? 5 : 10));
    return nice * pow;
  }

  function drawPullGraph(ctx, it, data) {
    var rows = extractRows(data, 30);
    var curves = rows.filter(function (r) { return r.pts.length > 1; });
    var x = it.x, y = it.y, w = it.w || 1128, h = it.h || 430, sz = it.size || 14;
    var padL = 62, padR = 26, padT = 18, padB = 46;
    var gx = x + padL, gy = y + padT, gw = Math.max(80, w - padL - padR), gh = Math.max(80, h - padT - padB);

    var maxX = Number(it.xMax) > 0 ? Number(it.xMax) : 0;
    var maxY = Number(it.yMax) > 0 ? Number(it.yMax) : 0;
    curves.forEach(function (c) {
      c.pts.forEach(function (p) {
        if (!(Number(it.xMax) > 0) && p[0] > maxX) maxX = p[0];
        if (!(Number(it.yMax) > 0) && p[1] > maxY) maxY = p[1];
      });
    });
    if (maxX <= 0) maxX = 14;
    if (maxY <= 0) maxY = 60;
    var yStep = niceStep(maxY * 1.08, 6);
    var yTop = Number(it.yMax) > 0 ? Number(it.yMax) : Math.ceil((maxY * 1.05) / yStep) * yStep;
    var xStep = niceStep(maxX, 7);
    var xTop = Number(it.xMax) > 0 ? Number(it.xMax) : Math.ceil(maxX / xStep) * xStep;

    // Frame
    ctx.strokeStyle = '#6b7280';
    ctx.lineWidth = 1;
    ctx.strokeRect(gx, gy, gw, gh);

    // Y grid + ticks
    for (var yv = 0; yv <= yTop + 1e-6; yv += yStep) {
      var py = gy + gh - (yv / yTop) * gh;
      if (yv > 0 && yv < yTop) line(ctx, gx, py, gx + gw, py, '#e5e7eb', 1);
      text(ctx, yv.toFixed(2), gx - 8, py + 4, 'right', sz, false, '#111111');
    }
    text(ctx, it.yLabel || 'kgf', gx - 42, gy + 4, 'left', sz, true, '#111111');

    // X grid + ticks
    for (var xv = 0; xv <= xTop + 1e-6; xv += xStep) {
      var px = gx + (xv / xTop) * gw;
      if (xv > 0 && xv < xTop) line(ctx, px, gy, px, gy + gh, '#f1f5f9', 1);
      text(ctx, String(Math.round(xv * 10) / 10), px, gy + gh + sz + 6, 'center', sz, false, '#111111');
    }
    text(ctx, it.xLabel || 'sec', gx + gw / 2, gy + gh + sz + 26, 'center', sz, true, '#111111');

    // Curves
    curves.forEach(function (c, ci) {
      var col = CURVE_COLORS[ci % CURVE_COLORS.length];
      ctx.beginPath();
      var peakPt = c.pts[0];
      c.pts.forEach(function (p, pi) {
        if (p[1] > peakPt[1]) peakPt = p;
        var cx = gx + Math.min(1, Math.max(0, p[0] / xTop)) * gw;
        var cy = gy + gh - Math.min(1, Math.max(0, p[1] / yTop)) * gh;
        if (pi === 0) ctx.moveTo(cx, cy); else ctx.lineTo(cx, cy);
      });
      ctx.strokeStyle = col;
      ctx.lineWidth = 1.6;
      ctx.stroke();

      // Peak X marker
      if (it.markers !== false && peakPt) {
        var mx = gx + Math.min(1, Math.max(0, peakPt[0] / xTop)) * gw;
        var my = gy + gh - Math.min(1, Math.max(0, peakPt[1] / yTop)) * gh;
        line(ctx, mx - 4, my - 4, mx + 4, my + 4, '#111111', 1.8);
        line(ctx, mx - 4, my + 4, mx + 4, my - 4, '#111111', 1.8);
      }

      // Curve number label at last point
      if (it.labels !== false && c.pts.length) {
        var last = c.pts[c.pts.length - 1];
        var lx = gx + Math.min(1, Math.max(0, last[0] / xTop)) * gw + 4;
        var ly = gy + gh - Math.min(1, Math.max(0, last[1] / yTop)) * gh + 4;
        text(ctx, c.TestNo, lx, ly, 'left', sz, true, col);
      }
    });
  }

  function bounds(layout, it, data) {
    var d = enrichData(data);
    if (it.type === 'text' || it.type === 'field') {
      var w = it.w || 300, h = (it.size || 18) + 8;
      var x = it.align === 'center' ? it.x - w / 2 : (it.align === 'right' ? it.x - w : it.x);
      return { x: x, y: it.y, w: w, h: h };
    }
    if (it.type === 'infogrid') return { x: it.x, y: it.y, w: it.w || 1128, h: measureInfoGrid(it) };
    if (it.type === 'pulltable') return { x: it.x, y: it.y, w: it.w || 1128, h: measurePullTable(it, d) };
    if (it.type === 'pullgraph') return { x: it.x, y: it.y, w: it.w || 1128, h: it.h || 430 };
    if (it.type === 'line') return { x: it.x, y: it.y - 4, w: it.w || 400, h: Math.max(10, (it.size || 1) + 8) };
    return { x: it.x || 0, y: it.y || 0, w: it.w || 200, h: it.h || 40 };
  }

  function render(canvas, layout, rawData) {
    var d = enrichData(rawData);
    var W = (layout && layout.w) || 1240, H = (layout && layout.h) || 1754;
    canvas.width = W; canvas.height = H;
    var ctx = canvas.getContext('2d');
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, W, H);
    ((layout && layout.items) || []).forEach(function (it) {
      if (it.type === 'text' || it.type === 'field') drawText(ctx, it, d);
      else if (it.type === 'infogrid') drawInfoGrid(ctx, it, d);
      else if (it.type === 'pulltable') drawPullTable(ctx, it, d);
      else if (it.type === 'pullgraph') drawPullGraph(ctx, it, d);
      else if (it.type === 'line') line(ctx, it.x, it.y, it.x + (it.w || 400), it.y, it.color || '#cbd5e1', it.size || 1);
    });
  }

  window.NxPullGraph = {
    CATEGORIES: CATEGORIES,
    catMeta: catMeta,
    defaultSources: defaultSources,
    defaultLayout: defaultLayout,
    render: render,
    bounds: bounds,
    enrichData: enrichData
  };
})();
