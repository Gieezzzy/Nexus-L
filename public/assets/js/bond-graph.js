/* Bonding Test-VF graph report: one renderer used by the Report Designer (preview) and by Shoe Bonding > Generate Report (PNG).
   A layout is { w, h, series: [...], items: [...] } in pixels of the page (A4 at 150 dpi = 1240 x 1754). Data is one row of
   tbl_dtr_bonding_points (merged with its tbl_dtr_bonding_info row): UTFpoint1.. , FTOpoint1.., UTFGraph "x;y;x;y", UTFSpots "x;y;x;y"... */
(function () {
  'use strict';

  var FONT = '"Times New Roman", Times, serif';

  var DEFAULT_SERIES = [
    { key: 'UTF', label: 'Upper To Foxing', points: 'UTFpoint', count: 'UTFCount', graph: 'UTFGraph', spots: 'UTFSpots', color: '#d62728', on: true },
    { key: 'FTO', label: 'Foxing To Outsole', points: 'FTOpoint', count: 'FTOCount', graph: 'FTOGraph', spots: 'FTOSpots', color: '#2ca02c', on: true },
    { key: 'FiTO', label: 'Filler To Outsole', points: 'FiTO', count: 'FiTOCount', graph: 'FiTOGraph', spots: 'FiTOSpots', color: '#1f77b4', on: true }
  ];

  function defaultLayout() {
    return {
      v: 1, w: 1240, h: 1754, series: JSON.parse(JSON.stringify(DEFAULT_SERIES)),
      items: [
        { id: 'title', type: 'text', x: 620, y: 38, w: 600, text: 'Bonding Test-VF', size: 46, bold: false, align: 'center', color: '#000000' },
        { id: 'equip', type: 'field', x: 68, y: 122, w: 500, template: 'Equip Code: {EquipmentCode}', size: 19, align: 'left', color: '#000000' },
        { id: 'shoe', type: 'field', x: 1170, y: 122, w: 600, template: '{ShoeName}', size: 19, align: 'right', color: '#000000' },
        { id: 'tests', type: 'tests', x: 60, y: 157, w: 1121, size: 19, rowH: 34, headH: 62, speed: '100', series: ['UTF', 'FTO', 'FiTO'] },
        { id: 'p1', type: 'points', x: 60, y: 354, w: 1111, size: 17, rowH: 46, headH: 62, from: 1, to: 15, series: ['UTF', 'FTO', 'FiTO'] },
        { id: 'p2', type: 'points', x: 60, y: 576, w: 1111, size: 17, rowH: 46, headH: 62, from: 16, to: 30, series: ['UTF', 'FTO', 'FiTO'] },
        { id: 'graph', type: 'graph', x: 60, y: 782, w: 1131, h: 612, series: ['UTF', 'FTO', 'FiTO'], yMax: 10, xMax: 0, markers: true, xLabel: 'sec', yLabel: 'kgf', size: 16 },
        { id: 'tech', type: 'field', x: 63, y: 1664, w: 360, template: 'Technician: {Technician}', size: 19, align: 'left', color: '#000000' },
        { id: 'mach', type: 'field', x: 443, y: 1664, w: 300, template: 'Machine No.: {EquipmentCode}', size: 19, align: 'left', color: '#000000' },
        { id: 'tested', type: 'field', x: 763, y: 1664, w: 170, template: 'Tested: {TestDate}', size: 19, align: 'left', color: '#000000' },
        { id: 'result', type: 'field', x: 943, y: 1664, w: 260, template: 'Result: {Result}  ({AgeCategory})', size: 19, bold: true, align: 'left', color: '#2e7d32', autoResult: true },
        { id: 'gen', type: 'field', x: 63, y: 1696, w: 1100, template: 'Lab ref {LabRefNo}  -  generated by NEXUS-L {now}', size: 14, align: 'left', color: '#8a8a8a' }
      ]
    };
  }

  // ---- data helpers
  function num(v) { var n = parseFloat(String(v == null ? '' : v).replace(',', '.')); return isFinite(n) ? n : null; }
  function xy(str) {                                  // "x;y;x;y" -> [[x, y], ...]
    var p = String(str || '').split(';'), out = [];
    for (var i = 0; i + 1 < p.length; i += 2) { var a = num(p[i]), b = num(p[i + 1]); if (a != null && b != null) out.push([a, b]); }
    return out;
  }
  function seriesOf(layout, key) { return (layout.series || []).filter(function (s) { return s.key === key; })[0] || null; }
  function activeSeries(layout, keys, data) {          // the series of this item that are on and have readings or a curve
    return (keys || []).map(function (k) { return seriesOf(layout, k); }).filter(function (s) {
      if (!s || s.on === false) return false;
      if (xy(data[s.graph]).length > 1) return true;
      for (var i = 1; i <= 45; i++) { if (num(data[s.points + i]) != null) return true; }
      return false;
    });
  }
  function pointCount(s, data) {
    var c = num(data[s.count]); if (c) return c;
    var m = 0; for (var i = 1; i <= 45; i++) { if (num(data[s.points + i]) != null) m = i; } return m;
  }
  function fill(tpl, data) {
    return String(tpl == null ? '' : tpl).replace(/\{([A-Za-z0-9_]+)\}/g, function (_, k) {
      if (k === 'now') { var d = new Date(), z = function (n) { return String(n).padStart(2, '0'); }; return d.getFullYear() + '-' + z(d.getMonth() + 1) + '-' + z(d.getDate()) + ' ' + z(d.getHours()) + ':' + z(d.getMinutes()); }
      var v = data[k]; return v == null ? '' : String(v);
    });
  }
  function resultColor(text) {
    var t = String(text).toUpperCase();
    if (/\bFAIL/.test(t)) return '#c62828';
    if (/\bTOL/.test(t)) return '#e65100';
    if (/\bPASS/.test(t)) return '#2e7d32';
    return null;
  }

  // ---- drawing helpers
  function font(ctx, size, bold) { ctx.font = (bold ? 'bold ' : '') + size + 'px ' + FONT; }
  function text(ctx, s, x, y, align, size, bold, color) {
    font(ctx, size, bold); ctx.fillStyle = color || '#000'; ctx.textAlign = align || 'left'; ctx.textBaseline = 'alphabetic';
    ctx.fillText(String(s), x, y);
  }
  function line(ctx, x1, y1, x2, y2, color, w) { ctx.beginPath(); ctx.moveTo(x1, y1); ctx.lineTo(x2, y2); ctx.strokeStyle = color || '#000'; ctx.lineWidth = w || 1; ctx.stroke(); }

  // ---- items
  function drawText(ctx, it, data) {
    var s = it.type === 'field' ? fill(it.template, data) : it.text, size = it.size || 19, col = it.color || '#000';
    if (it.autoResult) col = resultColor(s) || col;
    var x = it.align === 'center' ? it.x : it.x;      // the box's anchor: left edge, centre or right edge
    text(ctx, s, x, it.y + size, it.align || 'left', size, !!it.bold, col);
  }
  function boxH(it) { return (it.size || 19) + 8; }

  function testsRows(layout, it, data) { return activeSeries(layout, it.series, data); }
  function measureTests(layout, it, data) { return (it.headH || 62) + (it.rowH || 34) * (testsRows(layout, it, data).length + 1); }
  function drawTests(ctx, layout, it, data) {
    var rows = testsRows(layout, it, data), size = it.size || 19, rh = it.rowH || 34, hh = it.headH || 62, w = it.w;
    var cols = [0.0892, 0.1517, 0.2231, 0.2943, 0.1162, 0.1255];                // Test No., Test date, Sample, ReportNo, Speed, Width
    var xs = [it.x]; cols.forEach(function (c) { xs.push(xs[xs.length - 1] + c * w); });
    var heads = [['Test No.'], ['Test date'], ['Sample'], ['ReportNo'], ['Speed', 'mm/min'], ['Width', 'mm']];
    var total = hh + rh * (rows.length + 1);
    ctx.strokeStyle = '#000'; ctx.lineWidth = 1; ctx.strokeRect(it.x, it.y, w, total);
    for (var c = 1; c < 6; c++) line(ctx, xs[c], it.y, xs[c], it.y + total);
    line(ctx, it.x, it.y + hh, it.x + w, it.y + hh);
    for (var r = 1; r <= rows.length; r++) line(ctx, it.x, it.y + hh + rh * r, it.x + w, it.y + hh + rh * r);
    heads.forEach(function (h, i) {
      var cx = (xs[i] + xs[i + 1]) / 2;
      h.forEach(function (t, k) { text(ctx, t, cx, it.y + 12 + size + k * (size + 7) + (h.length === 1 ? 4 : 0), 'center', size, false); });
    });
    var wd = num(data.Width);
    rows.concat([null]).forEach(function (s, i) {
      var y = it.y + hh + rh * i + rh - 9;
      if (!s) { ['---', '---', '---', '---', '---', '---'].forEach(function (t, k) { text(ctx, t, k === 0 ? xs[k] + 8 : (k === 1 ? (xs[k] + xs[k + 1]) / 2 : xs[k + 1] - 10), y, k === 0 ? 'left' : (k === 1 ? 'center' : 'right'), size, false); }); return; }
      text(ctx, String(i + 1), xs[0] + 8, y, 'left', size, false);
      text(ctx, data.TestDate || '', (xs[1] + xs[2]) / 2, y, 'center', size, false);
      text(ctx, s.label, xs[3] - 10, y, 'right', size, false);
      text(ctx, data.LabRefNo || '', xs[4] - 10, y, 'right', size, false);
      text(ctx, String(it.speed || '100'), xs[5] - 10, y, 'right', size, false);
      text(ctx, wd != null ? wd.toFixed(2) : '', xs[6] - 10, y, 'right', size, false);
    });
  }

  function measurePoints(layout, it, data) { return (it.headH || 62) + (it.rowH || 46) * (activeSeries(layout, it.series, data).length + 1); }
  function drawPoints(ctx, layout, it, data) {
    var rows = activeSeries(layout, it.series, data), size = it.size || 17, rh = it.rowH || 46, hh = it.headH || 62, w = it.w;
    var from = Math.max(1, it.from || 1), to = Math.max(from, it.to || from), n = to - from + 1, cw = w / n;
    var total = hh + rh * (rows.length + 1);
    ctx.strokeStyle = '#000'; ctx.lineWidth = 1; ctx.strokeRect(it.x, it.y, w, total);
    for (var c = 1; c < n; c++) line(ctx, it.x + cw * c, it.y, it.x + cw * c, it.y + total);
    line(ctx, it.x, it.y + hh, it.x + w, it.y + hh);
    for (var r = 1; r <= rows.length; r++) line(ctx, it.x, it.y + hh + rh * r, it.x + w, it.y + hh + rh * r);
    for (var i = 0; i < n; i++) {
      var cx = it.x + cw * i + cw / 2;
      text(ctx, 'point' + (from + i), cx, it.y + hh / 2 - 6, 'center', size, false);
      text(ctx, 'kgf/cm', cx, it.y + hh / 2 + size + 2, 'center', size, false);
      rows.forEach(function (s, ri) {
        var v = num(data[s.points + (from + i)]);
        text(ctx, v != null ? v.toFixed(2) : '---', cx, it.y + hh + rh * ri + rh / 2 + 7, 'center', size + 3, false);
      });
      text(ctx, '---', cx, it.y + hh + rh * rows.length + rh / 2 + 7, 'center', size + 3, false);
    }
  }

  function drawGraph(ctx, layout, it, data) {
    var series = activeSeries(layout, it.series, data).filter(function (s) { return xy(data[s.graph]).length > 1; });
    var size = it.size || 16, L = 65, T = 38, R = 16, B = 52;                 // room for the axis numbers and labels
    var px = it.x + L, py = it.y + T, pw = it.w - L - R, ph = it.h - T - B;
    var curves = series.map(function (s) { return { s: s, c: xy(data[s.graph]), m: xy(data[s.spots]) }; });
    var maxX = 0, maxY = it.yMax || 10;
    curves.forEach(function (o) { o.c.forEach(function (p) { if (p[0] > maxX) maxX = p[0]; if (p[1] > maxY) maxY = p[1]; }); o.m.forEach(function (p) { if (p[0] > maxX) maxX = p[0]; }); });
    var xTop = it.xMax > 0 ? it.xMax : Math.max(100, Math.ceil(maxX / 100) * 100);
    var yTop = Math.max(it.yMax || 10, Math.ceil(maxY / 2) * 2);
    var X = function (v) { return px + v / xTop * pw; }, Y = function (v) { return py + ph - v / yTop * ph; };
    text(ctx, it.yLabel || 'kgf', it.x + 14, it.y + 14, 'left', size, false);
    ctx.save(); ctx.beginPath(); ctx.rect(px, py, pw, ph); ctx.clip();
    for (var gx = 0; gx <= xTop; gx += 100) line(ctx, X(gx), py, X(gx), py + ph, '#bdbdbd', 1);
    for (var gy = 0; gy <= yTop; gy += 2) line(ctx, px, Y(gy), px + pw, Y(gy), '#bdbdbd', 1);
    curves.forEach(function (o) {
      ctx.beginPath(); o.c.forEach(function (p, i) { if (i) ctx.lineTo(X(p[0]), Y(p[1])); else ctx.moveTo(X(p[0]), Y(p[1])); });
      ctx.strokeStyle = o.s.color || '#d62728'; ctx.lineWidth = 1.4; ctx.stroke();
    });
    if (it.markers !== false) curves.forEach(function (o) {
      o.m.forEach(function (p) { var a = X(p[0]), b = Y(p[1]); line(ctx, a - 6, b - 6, a + 6, b + 6, '#000', 1.5); line(ctx, a - 6, b + 6, a + 6, b - 6, '#000', 1.5); });
    });
    ctx.restore();
    ctx.strokeStyle = '#8c8c8c'; ctx.lineWidth = 1; ctx.strokeRect(px, py, pw, ph);
    for (var tx = 0; tx <= xTop; tx += 100) text(ctx, String(tx), X(tx), py + ph + size + 6, 'center', size, false);
    for (var ty = 0; ty <= yTop; ty += 2) text(ctx, ty.toFixed(2), px - 8, Y(ty) + 5, 'right', size, false);
    text(ctx, it.xLabel || 'sec', px + pw / 2, py + ph + size * 2 + 8, 'center', size, false);
    curves.forEach(function (o, i) { var last = o.c[o.c.length - 1]; if (last && i === 0) text(ctx, String(1), X(last[0]) + 8, Y(last[1]) + 5, 'left', size, false, o.s.color); });
    if (!curves.length) text(ctx, 'No curve data for this Lab Ref', px + pw / 2, py + ph / 2, 'center', size + 4, false, '#9e9e9e');
  }

  function drawLine(ctx, it) { line(ctx, it.x, it.y, it.x + (it.w || 100), it.y, it.color || '#000', it.size || 1); }

  function measure(layout, it, data) {
    if (it.type === 'tests') return measureTests(layout, it, data || {});
    if (it.type === 'points') return measurePoints(layout, it, data || {});
    if (it.type === 'graph') return it.h || 600;
    if (it.type === 'line') return 4;
    return boxH(it);
  }
  /** the box an item occupies on the page (used by the designer for the draggable frames) */
  function bounds(layout, it, data) {
    var h = measure(layout, it, data), w = it.w || 200, x = it.x;
    if ((it.type === 'text' || it.type === 'field')) {
      var c = document.createElement('canvas').getContext('2d'); font(c, it.size || 19, !!it.bold);
      var s = it.type === 'field' ? fill(it.template, data || {}) : it.text; w = Math.max(30, Math.ceil(c.measureText(String(s)).width) + 4);
      if (it.align === 'center') x = it.x - w / 2; else if (it.align === 'right') x = it.x - w;
    }
    return { x: x, y: it.y, w: w, h: h };
  }

  /**
   * The tables grow with the readings (one row per curve that has data, plus the "---" row), so a layout drawn for two curves overlaps when a Lab Ref has three:
   * the tests table runs into the first points table, that one into the second, the second into the graph. Every item that starts below a table is moved down
   * just far enough to stay clear of it (items already clear of it stay where the layout puts them); the footer stays at the bottom and the graph gets shorter
   * if it would reach it. Returns [{it, y, h}] in drawing order.
   */
  function reflow(layout, data) {
    var items = (layout.items || []).map(function (it, i) { return { it: it, i: i, y: it.y, h: null }; });
    var order = items.slice().sort(function (a, b) { return (a.it.y - b.it.y) || (a.i - b.i); });
    var pageH = layout.h || 1754, footerY = pageH - 200, gap = 10, push = 0, floor = 0, lastDynY = -1;
    order.forEach(function (o) {
      var it = o.it, y = it.y + push;
      if (it.y >= footerY && it.type !== 'graph') { o.y = it.y; return; }          // the footer (technician, machine, result ...) stays at the bottom
      if (floor && it.y > lastDynY + 5 && y < floor + gap) { push += floor + gap - y; y = it.y + push; }
      o.y = y;
      if (it.type === 'tests' || it.type === 'points') { floor = y + measure(layout, it, data || {}); lastDynY = it.y; }
      if (it.type === 'graph') {
        var h = it.h || 600, limit = footerY - 10;
        if (y + h > limit) h = Math.max(300, limit - y);
        o.h = h;
      }
    });
    return items;
  }

  function render(canvas, layout, data, opts) {
    layout = layout || defaultLayout(); data = data || {};
    canvas.width = layout.w || 1240; canvas.height = layout.h || 1754;
    var ctx = canvas.getContext('2d');
    ctx.fillStyle = '#ffffff'; ctx.fillRect(0, 0, canvas.width, canvas.height);
    reflow(layout, data).forEach(function (o) {
      var it = o.y === o.it.y && o.h == null ? o.it : Object.assign({}, o.it, { y: o.y }, o.h != null ? { h: o.h } : {});
      try {
        if (it.type === 'text' || it.type === 'field') drawText(ctx, it, data);
        else if (it.type === 'tests') drawTests(ctx, layout, it, data);
        else if (it.type === 'points') drawPoints(ctx, layout, it, data);
        else if (it.type === 'graph') drawGraph(ctx, layout, it, data);
        else if (it.type === 'line') drawLine(ctx, it);
      } catch (e) { if (window.console) console.warn('[bond-graph]', it.id, e); }
    });
    return canvas;
  }

  window.NxBondGraph = { render: render, reflow: reflow, defaultLayout: defaultLayout, bounds: bounds, xy: xy, fill: fill, DEFAULT_SERIES: DEFAULT_SERIES };
})();
