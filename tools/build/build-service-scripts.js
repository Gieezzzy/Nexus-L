// Cuts the functions that run inside the InterLink page out of the browser extension's background.js, so the background service
// (tools/interlink-service) runs exactly the same page logic. Each function starts at a line "function NAME" / "async function NAME"
// and ends at the next line that is a lone "}" in column 0. Functions only the service uses are in service-extra.js.
const fs = require('fs');
const path = require('path');

const lines = (file) => fs.readFileSync(file, 'utf8').split(/\r?\n/);
const src = lines(path.join(__dirname, '..', 'interlink-sender', 'background.js'));
const NAMES = ['gridProbe', 'goToGridFromHome', 'searchAndOpenUpload', 'fillAndAttach', 'pressCommit', 'forceSave', 'checkSubmitted'];

const out = ['// GENERATED by tools/build/build-service-scripts.js from tools/interlink-sender/background.js - do not edit by hand.', 'window.__nx = (() => {'];
for (const name of NAMES) {
  const start = src.findIndex((l) => l.startsWith(`function ${name}(`) || l.startsWith(`async function ${name}(`));
  if (start < 0) throw new Error(`function ${name} not found in background.js`);
  let end = start;
  while (end < src.length && src[end] !== '}') end++;
  if (end >= src.length) throw new Error(`end of ${name} not found`);
  out.push(...src.slice(start, end + 1));
}
out.push(...lines(path.join(__dirname, 'service-extra.js')).filter((l) => !l.startsWith('//')));
NAMES.push('readGridRow');
out.push(`  return { ${NAMES.join(', ')} };`, '})();', '');
const target = path.join(__dirname, '..', 'interlink-service', 'Scripts', 'interlink-core.js');
fs.writeFileSync(target, out.join('\n'));
console.log('wrote', target, out.length, 'lines');
